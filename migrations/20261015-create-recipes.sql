CREATE TABLE IF NOT EXISTS gym."Recipe" (
  id SERIAL PRIMARY KEY,
  title VARCHAR(120) NOT NULL,
  summary VARCHAR(400) NOT NULL DEFAULT '',
  image_url VARCHAR(500),
  tags JSONB NOT NULL DEFAULT '[]'::jsonb,
  prep_minutes INTEGER NOT NULL CHECK (prep_minutes BETWEEN 1 AND 600),
  servings INTEGER NOT NULL DEFAULT 1 CHECK (servings BETWEEN 1 AND 50),
  calories INTEGER NOT NULL CHECK (calories BETWEEN 0 AND 5000),
  protein_grams INTEGER NOT NULL CHECK (protein_grams BETWEEN 0 AND 500),
  carbs_grams INTEGER NOT NULL CHECK (carbs_grams BETWEEN 0 AND 800),
  fat_grams INTEGER NOT NULL CHECK (fat_grams BETWEEN 0 AND 500),
  ingredients JSONB NOT NULL DEFAULT '[]'::jsonb,
  steps JSONB NOT NULL DEFAULT '[]'::jsonb,
  is_published BOOLEAN NOT NULL DEFAULT TRUE,
  is_featured BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS recipe_published_idx
  ON gym."Recipe"(is_published, created_at DESC);

CREATE TABLE IF NOT EXISTS gym."RecipeFavorite" (
  id SERIAL PRIMARY KEY,
  member_id INTEGER NOT NULL REFERENCES gym."Member"(id) ON UPDATE CASCADE ON DELETE CASCADE,
  recipe_id INTEGER NOT NULL REFERENCES gym."Recipe"(id) ON UPDATE CASCADE ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (member_id, recipe_id)
);
